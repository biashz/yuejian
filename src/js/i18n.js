/// 英文日期用短月份名，中文仍保持「M 月 D 日」
const EN_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

let currentLanguage = "zh";

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  currentLanguage = MESSAGES[language] ? language : "zh";
  const root = document.documentElement;
  root.lang = currentLanguage === "zh" ? "zh-CN" : currentLanguage;
  root.dataset.lang = currentLanguage;
  return currentLanguage;
}

/** 取文案：支持 {name} 占位，缺失时回退中文，再缺失则返回 key 便于定位 */
export function t(key, params) {
  const dict = MESSAGES[currentLanguage] || MESSAGES.zh;
  let text = dict[key];
  if (text === undefined) text = MESSAGES.zh[key];
  if (text === undefined) return key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}

/** 把静态文案的短日期（月 + 日）按当前语言拼出来 */
export function formatMonthDay(month, day) {
  if (currentLanguage === "en") return `${EN_MONTHS[month]} ${day}`;
  return `${month + 1} 月 ${day} 日`;
}

/**
 * 给带 data-i18n* 属性的节点填充文案。
 * 只处理叶子节点：data-i18n 用 textContent，data-i18n-html 用 innerHTML。
 */
export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.title = t("app.title");
}
